public class contohTipeData30 {
    public static void main(String[] args) {
        char golDarah = 'A';
        byte jarak = (byte) 130;
        short jumlahPenduduk = 1025;
        float suhu = 60.50F;
        double berat = 0.546781234;
        long saldo = 15000000;
        int angkaDesimal = 0x10;

        System.out.println("Golongan Darah \t\t\t\t: " + (byte)golDarah);
        System.out.println("Jarak \t\t\t\t\t: " + jarak);
        System.out.println("Jumlah penduduk dalam satu dusun \t: " + jumlahPenduduk);
        System.out.println("Suhu \t\t\t\t\t: " + (float)suhu);
        System.out.println("Berat \t\t\t\t\t: " + berat);
        System.out.println("Saldo \t\t\t\t\t: " + saldo);
        System.out.println("Angka desimal \t\t\t\t: " + angkaDesimal);
    }
}
